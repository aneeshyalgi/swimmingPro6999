"""Every swim session from the coach programs, transcribed line for line (see coach_programs.py).

Generated once from the coach PDFs and reviewed by hand against every page; the app never reads the PDFs.
Each session: type, number, sections (name + prescription lines exactly as the coach wrote them) and, where the coach
stated it, the total volume in metres. Ligatures/typos fixed: "off", "effort", "buoy", "Stretch", "Paddles".
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Section:
    name: str                      # Warm-Up | Pre-Set | Main-Set | Warm-Down | Working Sets | Gym | Notes
    lines: tuple[str, ...]


@dataclass(frozen=True)
class Session:
    type: str
    number: int
    sections: tuple[Section, ...]
    stated_volume_m: int | None = None


def _s(type_: str, number: int, *sections: tuple[str, tuple[str, ...]], volume: int | None = None) -> Session:
    return Session(type_, number, tuple(Section(name, lines) for name, lines in sections), volume)


